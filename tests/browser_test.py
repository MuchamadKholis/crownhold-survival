"""Crownhold end-to-end browser test (headless Chromium via Playwright).
Run:  python3 tests/browser_test.py [path/to/index.html]
Real clicks for the main flows; game state is inspected through window.CH."""
import sys, os
from playwright.sync_api import sync_playwright
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
URL = 'file://' + os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'index.html'))
SHOTS = os.environ.get('SHOTS', '/tmp/ch_shots'); os.makedirs(SHOTS, exist_ok=True)
results, errors = [], []
def check(name, cond, info=''):
    results.append((name, bool(cond))); print(('  PASS ' if cond else '  FAIL ') + name + ('  [' + str(info) + ']' if info and not cond else ''))
def scr(pg, wx, wy):
    return pg.evaluate("([x,y])=>{const v=CH.App.view,r=v.canvas.getBoundingClientRect(),p=v.toScreen(x,y);return {x:r.left+p.x,y:r.top+p.y}}", [wx, wy])
def shot(pg, n): pg.screenshot(path=SHOTS + '/' + n + '.png')
FAST = """(sec)=>{const b=CH.App.battle; for(let i=0;i<sec*60&&!b.result;i++){b.update(1/60);
  if(i%30===0){ if(b.mode==='campaign'){ for(let ty=0;ty<21;ty++)for(let tx=0;tx<29;tx++) if(b.gold>=100&&b.nearRoad(tx,ty,1)&&b.canPlaceTower(tx,ty)) b.placeTower('archerTower',tx,ty); for(const t of b.buildings) if(t.placed&&b.towerUpgradeCost(t)!==null&&b.gold>b.towerUpgradeCost(t)+150) b.upgradeTower(t);}
    if(b.canCallWave&&b.canCallWave()&&!b.units.some(u=>u.side==='atk')) b.callWave(); if(b.pendingBoon) b.chooseBoon(b.pendingBoon[0].id);} }
  return {result:b.result, reason:b.reason}}"""

with sync_playwright() as p:
    br = p.chromium.launch(); pg = br.new_page(viewport={'width': 1366, 'height': 800})
    pg.on('pageerror', lambda e: errors.append('pageerror: ' + str(e)))
    pg.on('console', lambda m: errors.append(m.type + ': ' + m.text) if m.type == 'error' and 'fonts' not in m.text and 'ERR_NAME' not in m.text else None)
    pg.goto(URL); pg.evaluate('localStorage.clear()'); pg.reload(); pg.wait_for_timeout(800)
    print('Boot & home')
    check('title screen shows', pg.is_visible('#t-play')); shot(pg, 'title')
    pg.click('#t-play'); pg.wait_for_timeout(400); pg.click('.modal [data-close]'); pg.wait_for_timeout(300)
    check('home kingdom visible with HUD and dock', pg.is_visible('#hud-gold') and pg.is_visible('[data-dock=campaign]'))
    check('HUD shows resources', pg.inner_text('#hud-gold') == '750' and pg.inner_text('#hud-gems') == '30')

    print('Building placement & construction')
    pg.click('[data-dock=build]'); pg.wait_for_timeout(300); shot(pg, 'shop')
    pg.click('[data-act=place][data-type=stoneQuarry]'); pg.wait_for_timeout(300)
    check('placement ghost appears', pg.evaluate('!!CH.Home.state.ghost') and pg.is_visible('#placebar'))
    spot = pg.evaluate("(()=>{const s=CH.App.save;const a=CH.State.area(s);for(let ty=a.y;ty<a.y+a.h-1;ty++)for(let tx=a.x;tx<a.x+a.w-1;tx++)if(CH.State.tilesFree(s,tx,ty,2))return {tx,ty};})()")
    blocked = scr(pg, (14.5) * 32, (10.5) * 32)
    pg.mouse.move(blocked['x'], blocked['y']); pg.wait_for_timeout(100)
    check('ghost over the castle is invalid', pg.evaluate('CH.Home.state.ghost.valid') is False)
    pt = scr(pg, (spot['tx'] + 1) * 32, (spot['ty'] + 1) * 32)
    stone0 = pg.evaluate('CH.App.save.res.gold')
    pg.mouse.move(pt['x'], pt['y']); pg.wait_for_timeout(100); shot(pg, 'placing')
    pg.mouse.click(pt['x'], pt['y']); pg.wait_for_timeout(300)
    q = pg.evaluate("(()=>{const b=CH.App.save.buildings.find(b=>b.type==='stoneQuarry');return b&&{lvl:b.level,job:!!b.job}})()")
    check('quarry placed by click, under construction', q and q['lvl'] == 0 and q['job'], q)
    check('build cost deducted', pg.evaluate('CH.App.save.res.gold') < stone0)
    check('builder now busy', pg.evaluate('CH.State.freeBuilders(CH.App.save)') == 0)
    pg.click('[data-dock=build]'); pg.wait_for_timeout(200)
    check('second building blocked while builder busy', 'busy' in pg.inner_text('[data-type=goldStorage]'))
    pg.click('[data-back]'); pg.wait_for_timeout(200)
    pg.mouse.click(pt['x'], pt['y']); pg.wait_for_timeout(300)
    shot(pg, 'construct')
    pg.click('[data-p=speed]'); pg.wait_for_timeout(300)
    check('finish-now with gems completes the building', pg.evaluate("CH.App.save.buildings.find(b=>b.type==='stoneQuarry').level") == 1)

    print('Upgrades')
    gm = pg.evaluate("(()=>{const b=CH.App.save.buildings.find(b=>b.type==='goldMine');return {x:(b.tx+1)*32,y:(b.ty+1)*32}})()")
    gp = scr(pg, gm['x'], gm['y']); pg.mouse.click(gp['x'], gp['y']); pg.wait_for_timeout(300)
    check('tapping a building opens its panel', pg.is_visible('#panel') and 'Gold Mine' in pg.inner_text('#panel'))
    pg.click('[data-p=upgrade]'); pg.wait_for_timeout(300); shot(pg, 'upgrade_dialog')
    check('upgrade interface compares levels', 'Level 1 → 2' in pg.inner_text('.modal-card'))
    pg.click('[data-up]'); pg.wait_for_timeout(300)
    check('upgrade starts a construction job', pg.evaluate("!!CH.App.save.buildings.find(b=>b.type==='goldMine').job"))
    pg.evaluate("CH.State.speedUp(CH.App.save, CH.App.save.buildings.find(b=>b.type==='goldMine').id)")
    check('upgrade raises real production', pg.evaluate("CH.BUILDINGS.goldMine.prod(CH.App.save.buildings.find(b=>b.type==='goldMine').level) > CH.BUILDINGS.goldMine.prod(1)"))

    print('Resources')
    pg.evaluate("CH.App.save.lastSeen -= 15*60*1000; CH.App.handleEvents(CH.State.tick(CH.App.save))")
    buf = pg.evaluate("CH.App.save.buildings.find(b=>b.type==='goldMine').buf")
    check('production accumulates while away (offline)', buf > 100, buf)
    cap = pg.evaluate("CH.BUILDINGS.goldMine.buf(CH.App.save.buildings.find(b=>b.type==='goldMine').level)")
    pg.evaluate("CH.App.save.lastSeen -= 48*3600*1000; CH.State.tick(CH.App.save)")
    check('production is capped (no unlimited generation)', pg.evaluate("CH.App.save.buildings.find(b=>b.type==='goldMine').buf") <= cap + 0.01)
    pg.wait_for_timeout(600); shot(pg, 'collect_bubbles')
    g0 = pg.evaluate('CH.App.save.res.gold'); pg.click('[data-p=close]'); pg.wait_for_timeout(100)
    pg.mouse.click(gp['x'], gp['y']); pg.wait_for_timeout(300)
    check('tapping a full mine collects gold', pg.evaluate('CH.App.save.res.gold') > g0)
    check('storage caps resources', pg.evaluate("CH.App.save.res.gold <= CH.State.capacity(CH.App.save,'gold')"))

    print('Moving')
    pg.click('[data-p=move]'); pg.wait_for_timeout(200)
    free = pg.evaluate("(()=>{const s=CH.App.save;const a=CH.State.area(s);for(let ty=a.y+a.h-3;ty>a.y;ty--)for(let tx=a.x+a.w-3;tx>a.x;tx--)if(CH.State.tilesFree(s,tx,ty,2))return {tx,ty};})()")
    fp = scr(pg, (free['tx'] + 1) * 32, (free['ty'] + 1) * 32)
    pg.mouse.click(fp['x'], fp['y']); pg.wait_for_timeout(200)
    m = pg.evaluate("(()=>{const b=CH.App.save.buildings.find(b=>b.type==='goldMine');return [b.tx,b.ty]})()")
    check('building moved to the clicked spot', m == [free['tx'], free['ty']], (m, free))

    print('Army')
    pg.click('#panel [data-p=close]') if pg.is_visible('#panel') else None
    pg.click('[data-dock=army]'); pg.wait_for_timeout(300)
    n0 = pg.evaluate('CH.App.save.army.swordsman||0')
    pg.click('[data-act=train][data-t=swordsman]'); pg.click('[data-act=train][data-t=swordsman]'); pg.wait_for_timeout(200)
    check('training queue fills', pg.evaluate('CH.App.save.train.length') == 2)
    shot(pg, 'army')
    pg.wait_for_timeout(3500)
    check('troops finish training over time', pg.evaluate('CH.App.save.army.swordsman') >= n0 + 1)
    pg.click('[data-back]'); pg.wait_for_timeout(200)

    print('Campaign')
    pg.click('[data-dock=campaign]'); pg.wait_for_timeout(400); shot(pg, 'campaign')
    check('six regions shown, five locked', pg.locator('.region-card').count() == 6 and pg.locator('.region-card.locked').count() == 5)
    pg.click('.region-card >> nth=0'); pg.wait_for_timeout(400); shot(pg, 'stages')
    check('six stages, later ones locked', pg.locator('.stage-card').count() == 6 and pg.locator('.stage-card.locked').count() == 5)
    check('locked stage cannot start', pg.locator('.stage-card >> nth=1').locator('button[disabled]').count() == 1)
    pg.click('[data-act=play][data-id="0-0"]'); pg.wait_for_timeout(700)
    check('campaign battle opens', pg.evaluate("CH.App.mode==='battle' && CH.App.battle.mode==='campaign'"))
    gold0 = pg.evaluate('CH.App.battle.gold')
    tp = pg.evaluate("(()=>{const b=CH.App.battle;for(let ty=0;ty<20;ty++)for(let tx=0;tx<28;tx++)if(b.nearRoad(tx,ty,1)&&b.canPlaceTower(tx,ty))return {tx,ty}})()")
    sp = scr(pg, (tp['tx'] + 1) * 32, (tp['ty'] + 1) * 32)
    pg.mouse.move(sp['x'], sp['y']); pg.mouse.click(sp['x'], sp['y']); pg.wait_for_timeout(200)
    check('tower placed with battle gold', pg.evaluate('CH.App.battle.buildings.filter(b=>b.placed).length') == 1 and pg.evaluate('CH.App.battle.gold') == gold0 - 100)
    rp = pg.evaluate("(()=>{const b=CH.App.battle;for(let i=0;i<b.road.length;i++)if(b.road[i]&&i%30>2)return {x:(i%30+0.5)*32,y:(Math.floor(i/30)+0.5)*32}})()")
    s2 = scr(pg, rp['x'], rp['y']); pg.mouse.click(s2['x'], s2['y']); pg.wait_for_timeout(200)
    check('cannot build on the road', pg.evaluate('CH.App.battle.buildings.filter(b=>b.placed).length') == 1)
    pg.click('#b-call'); pg.wait_for_timeout(1500); shot(pg, 'campaign_battle')
    check('wave starts and enemies follow the road', pg.evaluate("CH.App.battle.units.some(u=>u.side==='atk'&&u.mode==='path')"))
    r = pg.evaluate(FAST, 400); pg.wait_for_timeout(1800)
    check('campaign stage 1-1 can be won', r['result'] == 'win', r)
    check('results screen shows', pg.is_visible('.results.win')); shot(pg, 'campaign_win')
    check('victory saved with stars and unlocks 1-2', pg.evaluate("CH.App.save.campaign['0-0']>=1 && CH.Campaign.stageUnlocked(CH.App.save,0,1)"))
    pg.click('[data-r=next]'); pg.wait_for_timeout(600)
    pg.evaluate("(()=>{const b=CH.App.battle;b.callWave();b.core.hp=1;const e=b.spawnUnit(CH.ENEMIES.orc,'atk',b.core.x-10,b.core.cy,{mode:'nav'});})()")
    pg.wait_for_timeout(3500)
    check('defeat when the castle falls', pg.is_visible('.results.lose')); shot(pg, 'campaign_lose')
    check('defeat does not unlock the next stage', not pg.evaluate("CH.Campaign.stageUnlocked(CH.App.save,0,2)"))
    pg.click('[data-r=home]'); pg.wait_for_timeout(300)

    print('Endless Raid')
    pg.click('[data-dock=endless]'); pg.wait_for_timeout(300)
    check('endless modes locked before castle level 2', pg.locator('.mode-card[disabled]').count() == 2)
    pg.evaluate("CH.App.save.buildings.find(b=>b.type==='castle').level=2; CH.App.save.army={swordsman:20,archer:16}; CH.UI.refreshSheet()")
    pg.wait_for_timeout(200); shot(pg, 'endless')
    pg.click('[data-act=raid]'); pg.wait_for_timeout(500); shot(pg, 'raid_targets')
    check('four AI opponents with previews and loot', pg.locator('.op-card').count() == 4)
    opid = pg.evaluate('CH.App.save.raid.opponents[0].id')
    pg.click('.op-card >> nth=0 >> [data-act=scout]'); pg.wait_for_timeout(400); shot(pg, 'raid_prep')
    pg.click('[data-act=attack]'); pg.wait_for_timeout(700)
    check('raid battle opens', pg.evaluate("CH.App.battle&&CH.App.battle.mode==='raid'"))
    shot(pg, 'raid_start')
    col = pg.evaluate("""(()=>{const b=CH.App.battle,v=CH.App.view;
      for(let tx=0;tx<30;tx++) for(let ty=0;ty<16;ty++){ let ok=true; for(let k=0;k<6;k++){const x=(tx+.5)*32,y=(ty+k+.5)*32,sp=v.toScreen(x,y); if(!b.canDeploy(x,y)||sp.x<10||sp.y<80||sp.x>v.w-10||sp.y>v.h-120) ok=false;}
        if(ok) return {x:(tx+.5)*32,y0:(ty+.5)*32,y1:(ty+5.5)*32}; } return null})()""")
    a = scr(pg, col['x'], col['y0']); b2 = scr(pg, col['x'], col['y1'])
    pg.mouse.move(a['x'], a['y']); pg.mouse.down(); pg.mouse.move(b2['x'], b2['y'], steps=12); pg.mouse.up(); pg.wait_for_timeout(200)
    dep = pg.evaluate("CH.App.battle.used.swordsman||0")
    check('drag deploys troops along the line', dep >= 3, dep)
    mid = scr(pg, 15 * 32, 11 * 32); pg.mouse.click(mid['x'], mid['y']); pg.wait_for_timeout(100)
    check('cannot deploy inside the red zone', pg.evaluate("CH.App.battle.used.swordsman||0") == dep)
    pg.evaluate("(()=>{const b=CH.App.battle;let k=0;for(const t of ['swordsman','archer'])while(b.army[t]>0){b.deployTroop(t,(1+(k%25))*32,(1+(k++%3))*32*0.5+16)}})()")
    pg.wait_for_timeout(2500); shot(pg, 'raid_mid')
    check('troops damage enemy buildings', pg.evaluate("CH.App.battle.buildings.some(b=>b.hp<b.maxHp)"))
    check('A* pathing: attackers pick building targets', pg.evaluate("CH.App.battle.units.some(u=>u.tb)"))
    tro0 = pg.evaluate('CH.App.save.raid.trophies'); res0 = pg.evaluate('CH.App.save.res.gold')
    pg.evaluate(FAST, 200); pg.wait_for_timeout(1800); shot(pg, 'raid_result')
    check('raid results screen', pg.is_visible('.results'))
    check('raid rewards trophies and loot', pg.evaluate('CH.App.save.raid.trophies') != tro0 and pg.evaluate('CH.App.save.res.gold') >= res0)
    check('raided opponent removed (no farming)', not pg.evaluate("CH.App.save.raid.opponents.some(o=>o.id===%r)" % opid))
    check('deployed troops are used up', pg.evaluate('(CH.App.save.army.swordsman||0)+(CH.App.save.army.archer||0)') == 0)
    pg.click('[data-r=home]'); pg.wait_for_timeout(300)

    print('Endless Defense')
    pg.evaluate("CH.App.save.heroes.king.unlocked=true; CH.App.startBattle({mode:'defense'})"); pg.wait_for_timeout(600)
    check('defense uses the real home layout', pg.evaluate("CH.App.battle.buildings.length") == pg.evaluate("CH.App.save.buildings.filter(b=>b.level>0&&CH.BUILDINGS[b.type].cat!=='obstacle').length"))
    pg.click('.b-card.hero'); hp = scr(pg, 15 * 32, 13.5 * 32); pg.mouse.click(hp['x'], hp['y']); pg.wait_for_timeout(200)
    check('hero deployed as a defender', pg.evaluate("!!CH.App.battle.heroesUsed.king"))
    pg.click('#b-call'); pg.wait_for_timeout(2500); shot(pg, 'defense')
    check('enemies attack from the edges', pg.evaluate("CH.App.battle.units.some(u=>u.side==='atk')"))
    pg.click('.b-card.hero'); pg.wait_for_timeout(100)
    pg.evaluate("(()=>{const b=CH.App.battle; for(let i=0;i<60*400&&!b.result&&b.wave<5;i++){b.update(1/60); if(i%30===0&&b.canCallWave()&&!b.units.some(u=>u.side==='atk'))b.callWave();}})()")
    pg.wait_for_timeout(1200)
    if pg.evaluate("CH.App.battle.wave>=5 && !CH.App.battle.result"):
        pg.evaluate("(()=>{const b=CH.App.battle; for(let i=0;i<60*120&&!b.pendingBoon&&!b.result;i++)b.update(1/60);})()"); pg.wait_for_timeout(500)
        check('blessing offered after wave 5', pg.is_visible('.boons')); shot(pg, 'boon')
        pg.click('.boon >> nth=0'); pg.wait_for_timeout(200)
    else: check('reached wave 5 to test blessings', False, pg.evaluate('CH.App.battle.wave'))
    pg.evaluate("(()=>{const b=CH.App.battle; const c=b.buildings.find(x=>x.type==='castle'); b.damageBuilding(c, 1e9)})()")
    pg.wait_for_timeout(1800); shot(pg, 'defense_result')
    check('defense ends when the castle falls, record saved', pg.is_visible('.results') and pg.evaluate('CH.App.save.defense.best') >= 4)
    check('real buildings undamaged after defense', pg.evaluate("CH.App.save.buildings.some(b=>b.type==='castle')"))
    pg.click('[data-r=home]'); pg.wait_for_timeout(300)

    print('Screens')
    for s in ['heroes', 'buildings', 'lab', 'resources', 'profile', 'settings', 'howto']:
        pg.evaluate("s=>{CH.UI.closeSheets();CH.UI.sheet(s)}", s); pg.wait_for_timeout(250); shot(pg, 'sheet_' + s)
        check('screen opens: ' + s, pg.is_visible('.sheet-body'))
    pg.evaluate('CH.UI.closeSheets()')

    print('Save & load')
    snap = pg.evaluate("JSON.stringify({c:CH.App.save.campaign,b:CH.App.save.buildings.length,t:CH.App.save.raid.trophies,best:CH.App.save.defense.best})")
    pg.evaluate('CH.App.persist()'); pg.reload(); pg.wait_for_timeout(800)
    after = pg.evaluate("JSON.stringify({c:CH.App.save.campaign,b:CH.App.save.buildings.length,t:CH.App.save.raid.trophies,best:CH.App.save.defense.best})")
    check('progress survives a reload', snap == after, (snap, after))
    fresh = pg.evaluate("(()=>{localStorage.setItem('crownhold.save.v1','{broken'); const a=CH.State.load(); localStorage.setItem('crownhold.save.v1', JSON.stringify({version:1,res:{gold:-5,gems:'x'},buildings:[{type:'nope'},{type:'castle',tx:999,ty:3}],heroes:{king:{level:99}}})); const b=CH.State.load(); CH.App.persist(); return a.buildings.some(x=>x.type==='castle')&&a.res.gems===30&&b.res.gold===0&&b.buildings.some(x=>x.type==='castle')&&b.heroes.king.level===10})()")
    check('corrupt or hostile save data falls back safely', fresh)

    print('Screen sizes')
    pg.reload(); pg.wait_for_timeout(600); pg.click('#t-play'); pg.wait_for_timeout(300)
    if pg.is_visible('.modal [data-close]'): pg.click('.modal [data-close]')
    for name, vp in [('laptop', (1280, 720)), ('phone', (390, 844)), ('phone_land', (844, 390))]:
        pg.set_viewport_size({'width': vp[0], 'height': vp[1]}); pg.wait_for_timeout(400); shot(pg, 'home_' + name)
        ok = pg.evaluate("(()=>{const d=document.getElementById('dock').getBoundingClientRect();return d.right<=innerWidth+1&&d.bottom<=innerHeight+1&&d.left>=-1})()")
        check('home fits: ' + name, ok)
        pg.evaluate("CH.App.startBattle({mode:'campaign',stage:CH.Campaign.stage(0,0)})"); pg.wait_for_timeout(400); shot(pg, 'battle_' + name)
        ok = pg.evaluate("(()=>{const d=document.getElementById('b-bar').getBoundingClientRect();return d.bottom<=innerHeight+1&&d.width>0})()")
        check('battle HUD fits: ' + name, ok)
        pg.evaluate("CH.App.goHome()")
    br.close()
check('no runtime errors in console', not errors, errors[:5])
fails = [r for r in results if not r[1]]
print('\n%d passed, %d failed' % (len(results) - len(fails), len(fails)))
sys.exit(1 if fails else 0)
